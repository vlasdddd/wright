# Описание: Playwright начинает следить за всеми сетевыми запросами браузера к адресу */**/api/v1/fruit
# Когда страница пытается загрузить список фруктов с сервера, запрос не уходит в сеть — вместо этого функция handle мгновенно возвращает поддельный JSON-ответ с одним фруктом: [{"name": "Strawberry", "id": 21}]
# Браузер переходит на демо-страницу https://demo.playwright.dev/api-mocking, которая запрашивает данные и получает нашу поддельную "клубнику"
# Тест проверяет, что на странице действительно отобразился текст "Strawberry" (и тест успешно завершается)
# Я скопировал пример из раздела "Guides/Mock APIs"

import pytest
from playwright.sync_api import Page, Route, expect


# Объявляем тестовую функцию, которая принимает объект страницы браузера (page)
def test_mock_the_fruit_api(page: Page):
    # Создаём функцию-обработчик для перехваченного сетевого запроса (route)
    def handle(route: Route):
        # Подготавливаем поддельные (моковые) данные в виде списка со словарём
        json = [{"name": "Strawberry", "id": 21}]
        # Отвечаем на перехваченный запрос нашими поддельными данными вместо обращения к реальному серверу
        route.fulfill(json=json)

    # Включаем перехват всех запросов по маске адреса "*/**/api/v1/fruits" и передаём их в функцию handle
    page.route("*/**/api/v1/fruits", handle)

    # Открываем в браузере тестовую страницу по указанному URL
    page.goto("https://playwright.dev")

    # Проверяем, что на странице появился и стал видимым элемент с текстом "Strawberry"
    expect(page.get_by_text("Strawberry")).to_be_visible()


if __name__ == "__main__":
    pytest.main(["-v", __file__])
